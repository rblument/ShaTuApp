package edu.regis.shatu.objectives;

import edu.regis.shatu.model.KnowledgeComponentKind;
import edu.regis.shatu.model.StepCompletion;
import edu.regis.shatu.model.Student;
import edu.regis.shatu.model.TutoringSession;
import edu.regis.shatu.model.aol.ProblemType;
import edu.regis.shatu.model.aol.StepSubType;
import edu.regis.shatu.model.steps.AddOneStep;
import edu.regis.shatu.svc.TutorReply;

public class AddOne extends Objective {
    /**
     * Message length used when no step data is sent.
     */
    static final int DEFAULT_MESSAGE_LENGTH = 35;

    /**
     * Longest message the client can ask for when the tutor makes the
     * question. Lower than the 1024 used by Encode ASCII because the Check
     * request carries the question twice and its binary answer up to three
     * times. At 120 a made-up question stays under the server's 8192
     * character limit even when every character is one Gson escapes, such
     * as <, with a correct answer and a 256 character user id made of the
     * plain characters the New User form allows. A very long typed answer
     * can still go over the limit.
     */
    static final int MAX_MESSAGE_LENGTH = 120;

    public AddOne(Student student) {
        super(student);
    }

    @Override
    public TutorReply hint(StepCompletion completion) {
        return genericHint(completion, KnowledgeComponentKind.ADD_ONE_BIT,
                "Add a single '1' bit to the end of the message");
    }

    /**
     * Handles client requests for a new add one bit example.
     *
     * @return a TutorReply
     */
    @Override
    public TutorReply example(TutoringSession session, String jsonData) {

        System.out.println("Start tutor newaddonebitexample");

        AddOneStep newAddOneBit = gson.fromJson(jsonData, AddOneStep.class);

        // If no prior data was passed in, create a fresh example.
        if (newAddOneBit == null) {
            newAddOneBit = new AddOneStep();
            newAddOneBit.setMessageLength(DEFAULT_MESSAGE_LENGTH);
        }

        // Add1View only sends the message length the student typed, so make
        // a question of that length.
        String question = newAddOneBit.getQuestion();
        if (question == null || question.isEmpty()) {
            int messageLength = newAddOneBit.getMessageLength();
            if (messageLength < 1 || messageLength > MAX_MESSAGE_LENGTH) {
                return createError("Enter a message length between 1 and "
                        + MAX_MESSAGE_LENGTH + ".", null);
            }
            question = generateRandomString(messageLength);
            newAddOneBit.setQuestion(question);
        }

        newAddOneBit.setMessageLength(question.length());
        newAddOneBit.setResult(addOneFunction(question));

        return genericExample(newAddOneBit, StepSubType.ADD_ONE_BIT, ProblemType.ADD_ONE_BIT,
                KnowledgeComponentKind.ADD_ONE_BIT,
                "Add one bit to the given bit string");
    }

    /**
     * This method is called from the AddOneView when the check button is
     * clicked, will check the users answer to the correct answer generated by
     * the newAddOneStep method in this file.
     * Grades the answer and updates the Assessment table (exposures, successes, hints).
     * The completed Step is persisted for the student, in the Unit matching their
     * tutoring mode (See One, Do One, Teach One), by ShaTuTutor.completedStep() using
     * CompletedStepSvc.
     *
     * @param completion
     *
     * @return
     */
    @Override
    public TutorReply completeStep(StepCompletion completion) {

        AddOneStep completedStep = gson.fromJson(completion.getData(), AddOneStep.class);

        // The student's answer comes in its own field. The correct answer is
        // worked out again from the question instead of trusting the copy
        // that came back from the client.
        // A missing answer is graded as wrong.
        String userAnswer = completedStep.getUserAnswer() == null ? "" : completedStep.getUserAnswer();
        String correctAnswer = addOneFunction(completedStep.getQuestion());

        return genericComplete(correctAnswer, userAnswer, KnowledgeComponentKind.ADD_ONE_BIT);
    }

    /**
     * This method takes the question from the newAddOneStep ad converts it to
     * binary and returns the binary answer.
     *
     * @param question
     *
     * @return
     */
    String addOneFunction(String question) {
        String answer;

        char stringArray[] = question.toCharArray();

        StringBuilder binary = new StringBuilder();

        for (int i = 0; i < stringArray.length; i++) {
            String binaryChar = String.format("%8s", Integer.toBinaryString(stringArray[i])).replaceAll(" ", "0");

            binary.append(binaryChar).append(" ");
        }

        answer = binary + "1";

        return answer;
    }

}